import { expect, test } from './e2e'
import { openSubscriptionAdd } from './fixtures/subscription-options'

test('subscription inbox presets, filters, saved views, and podcast add stay in the intended context', async ({ page }) => {
  await page.goto('/subscriptions?mode=history')
  const inbox = page.getByRole('region', { name: '历史收件箱' })
  const presets = page.getByRole('navigation', { name: '常用订阅筛选' })
  await expect(inbox).toBeVisible()
  await expect(presets.getByRole('button', { name: /本周视频/ })).toBeVisible()
  await expect(page.getByRole('group', { name: '自定义订阅视图' })).toHaveCount(0)

  await presets.getByRole('button', { name: /本周视频/ }).click()
  await expect(page).toHaveURL(/\/subscriptions\?view=/)
  await inbox.getByRole('searchbox', { name: '搜索历史内容' }).fill('测试筛选')
  await inbox.getByRole('button', { name: '应用筛选' }).click()
  await expect(page).toHaveURL('/subscriptions?mode=history')
  await expect(inbox.getByRole('searchbox', { name: '搜索历史内容' })).toHaveValue('测试筛选')

  await inbox.getByRole('button', { name: '保存为视图' }).click()
  await inbox.getByRole('textbox', { name: '视图名称' }).fill('测试视图')
  await inbox.getByRole('button', { name: '保存视图', exact: true }).click()
  await expect(page).toHaveURL(/\/subscriptions\?view=/)
  await expect(page.getByRole('group', { name: '自定义订阅视图' }).getByRole('button', { name: /测试视图/ })).toBeVisible()

  await openSubscriptionAdd(page)
  await expect(page.locator('#subscription-add-toggle')).toHaveAttribute('aria-expanded', 'true')
  await page.getByLabel('订阅地址').fill('https://rss-fixture.example/feed.xml')
  await expect(page.locator('.add-source-confirm')).toContainText('RSS / 播客')
  await expect(page).toHaveURL(/\/subscriptions\?view=/)
})

test('subscription cards load full local articles only for reading and saving', async ({ page, request }) => {
  const added = await request.post('/api/subscriptions', { data: { type: 'rss', query: 'https://rss-fixture.example/card-projection.xml' } })
  expect(added.ok()).toBe(true)
  const { source } = await added.json()
  expect((await request.post(`/api/subscriptions/${encodeURIComponent(source.id)}/update`)).ok()).toBe(true)
  const details: string[] = []
  page.on('request', request => {
    const path = new URL(request.url()).pathname
    if (path.startsWith('/api/subscription-inbox/')) details.push(path)
  })
  const cards = page.waitForResponse(response => new URL(response.url()).pathname === '/api/subscription-inbox' && new URL(response.url()).searchParams.get('cards') === 'true')
  await page.goto('/subscriptions?mode=history')
  const listing = await (await cards).json()
  const article = listing.page.entries.find((entry: { item: { kind: string } }) => entry.item.kind === 'article').item
  expect(article.partial).toBe(true)
  expect(article.articleBlocks ?? []).toEqual([])
  const card = page.getByTestId('content-card').filter({ has: page.getByRole('heading', { name: 'RSS 测试文章', exact: true }) })
  await expect(card).toBeVisible()
  expect(details).toEqual([])
  await card.getByRole('button', { name: '阅读 RSS 测试文章', exact: true }).click()
  await expect(page.getByRole('button', { name: '返回列表', exact: true })).toBeVisible()
  await expect(page.getByText('第二段正文。', { exact: true })).toBeVisible()
  expect(details).toHaveLength(1)
  await page.getByRole('button', { name: '返回列表', exact: true }).click()
  await card.getByRole('button', { name: '收藏 RSS 测试文章', exact: true }).click()
  await expect(card.getByRole('button', { name: '取消收藏 RSS 测试文章', exact: true })).toBeEnabled()
  const saved = await (await request.get(`/api/library/${encodeURIComponent(article.id)}`)).json()
  expect(saved.partial).toBeFalsy()
  expect(saved.articleBlocks.some((block: { text?: string }) => block.text === '第二段正文。')).toBe(true)
  await page.goto('/subscriptions?view=builtin-unread')
  await expect(page.getByRole('region', { name: '历史收件箱' })).toBeVisible()
  await expect(page.getByTestId('content-card').filter({ has: page.getByRole('heading', { name: 'RSS 测试文章', exact: true }) })).toHaveCount(0)
})

test('single-source reads and updates keep cards light and retain full local articles', async ({ page, request }) => {
  const added = await request.post('/api/subscriptions', { data: { type: 'rss', query: 'https://rss-fixture.example/single-source-cards.xml' } })
  expect(added.ok()).toBe(true)
  const { source } = await added.json()
  const refreshed = await request.post(`/api/subscriptions/${encodeURIComponent(source.id)}/update`)
  expect(refreshed.ok()).toBe(true)
  await page.addInitScript(id => sessionStorage.setItem('tangentry-subscription-selection', id), source.id)
  const localReads: string[] = []
  page.on('request', request => {
    const path = new URL(request.url()).pathname
    if (path.startsWith('/api/subscription-inbox/')) localReads.push(path)
  })
  const listingResponse = page.waitForResponse(response => new URL(response.url()).pathname === `/api/subscriptions/${encodeURIComponent(source.id)}` && new URL(response.url()).searchParams.get('cards') === 'true')
  await page.goto('/subscriptions')
  const listing = await (await listingResponse).json()
  const article = listing.items.find((item: { kind: string }) => item.kind === 'article')
  expect(article.partial).toBe(true)
  expect(article.articleBlocks ?? []).toEqual([])
  const card = page.getByTestId('content-card').filter({ has: page.getByRole('heading', { name: 'RSS 测试文章', exact: true }) })
  await expect(card).toBeVisible()
  expect(localReads).toEqual([])
  const updateResponse = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname.endsWith('/update') && new URL(response.url()).searchParams.get('cards') === 'true')
  await page.getByRole('region', { name: '来源投稿', exact: true }).getByRole('button', { name: '更新投稿', exact: true }).click()
  const updated = await (await updateResponse).json()
  expect(updated.items.find((item: { id: string }) => item.id === article.id).partial).toBe(true)
  expect(localReads).toEqual([])
  const detailResponse = page.waitForResponse(response => new URL(response.url()).pathname === `/api/subscription-inbox/${encodeURIComponent(article.id)}`)
  await card.getByRole('button', { name: '阅读 RSS 测试文章', exact: true }).click()
  const detail = await (await detailResponse).json()
  expect(detail.partial).toBeFalsy()
  expect(detail.articleBlocks.some((block: { text?: string }) => block.text === '第二段正文。')).toBe(true)
  await expect(page.getByText('第二段正文。', { exact: true })).toBeVisible()
  expect(localReads).toHaveLength(1)
  const full = await (await request.get(`/api/subscriptions/${encodeURIComponent(source.id)}`)).json()
  expect(full.items.find((item: { id: string }) => item.id === article.id).articleBlocks.some((block: { text?: string }) => block.text === '第二段正文。')).toBe(true)
})

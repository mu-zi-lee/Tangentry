// Actual playable synthetic H.264/AAC file, actual HTTP/SQLite and native browser
// media clock. External platform/CLI metadata are labelled E2E fixtures.
async function completed(request: APIRequestContext, id: string, title: string, maxHeight = 720): Promise<DownloadJob> {
  const response = await request.post('/api/downloads', { data: { url: id, title, maxHeight } })
  expect(response.status()).toBe(202)
  const job = await response.json() as DownloadJob
  await expect.poll(async () => {
    const result = await (await request.get('/api/downloads')).json() as { jobs: DownloadJob[] }
    return result.jobs.find(item => item.id === job.id)?.state
  }, { timeout: 10000 }).toBe('completed')
  return job
}

test.beforeEach(async ({ request }) => {
  for (const id of ['BVplayer0000', 'BVfollow0000', 'BVbroken0000']) {
    const { notes } = await (await request.get(`/api/notes?contentId=bilibili%3A${id}`)).json()
    for (const note of notes) await request.delete(`/api/notes/${note.id}`)
  }
})


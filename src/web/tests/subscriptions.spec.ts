import { expect, test } from './e2e'
import AxeBuilder from '@axe-core/playwright'
import type { SubscriptionDetail, SubscriptionSource, ContentItem } from '../src/shared/api/types'
import { closeSubscriptionSettings, openSubscriptionAdd } from './fixtures/subscription-options'

// All subscription endpoints use the actual app / HTTP / SQLite. Only external
// platform I/O is replaced by the test server's explicitly labelled provider.
test.beforeEach(async ({ request }) => {
  const { sources } = await (await request.get('/api/subscriptions')).json() as { sources: SubscriptionSource[] }
  for (const source of sources) await request.delete(`/api/subscriptions/${encodeURIComponent(source.id)}`)
  const { items } = await (await request.get('/api/library')).json() as { items: ContentItem[] }
  for (const item of items) await request.delete(`/api/library/${encodeURIComponent(item.id)}`)
})

test('subscriptions persist and update independently, keep successful content on failure, and restore reading context', async ({ page, request }) => {
  await page.route('**/api/subscriptions/resolve', route => {
    const query = route.request().postDataJSON().query
    const id = query.includes('12345') ? '12345' : '67890'
    return route.fulfill({ json: { type: 'bilibili', query: id, title: '测试来源名称', url: 'https://space.bilibili.com/' + id } })
  })
  const beforeJobs = (await (await request.get('/api/downloads')).json()).jobs
  await page.goto('/subscriptions')
  await expect(page.getByRole('heading', { name: '全部订阅', exact: true })).toBeVisible()
  await page.getByLabel('订阅地址').fill('https://space.bilibili.com/12345')
  await page.getByLabel('订阅来源名称', { exact: true }).fill('知识视频')
  await page.getByRole('button', { name: '保存来源', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '来源已保存' })).toBeVisible()
  const path = '/api/subscriptions/bilibili%3Acreator%3A12345'
  const local = await (await request.get(path)).json() as SubscriptionDetail
  expect(local.source.lastUpdatedAt).toBe(0)
  expect(local.items).toEqual([])
  await page.getByLabel('订阅地址').fill('12345')
  await page.getByLabel('订阅来源名称', { exact: true }).fill('重复不应改名')
  await page.getByRole('button', { name: '保存来源', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '这个来源已存在' })).toBeVisible()
  expect((await (await request.get('/api/subscriptions')).json()).sources).toHaveLength(1)
  await expect(page.getByRole('heading', { name: '知识视频', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '重命名来源' }).click()
  await expect(page.getByLabel('来源新名称')).toBeFocused()
  await page.getByLabel('来源新名称').fill('知识视频 · 持续学习')
  await page.getByRole('button', { name: '保存名称' }).click()
  await expect(page.getByRole('heading', { name: '知识视频 · 持续学习', exact: true })).toBeVisible()
  await closeSubscriptionSettings(page)
  await page.getByRole('button', { name: '更新投稿', exact: true }).click()
  await expect(page.getByTestId('content-card')).toHaveCount(1)
  await page.getByRole('button', { name: '更新投稿', exact: true }).click()
  await expect(page.getByTestId('content-card')).toHaveCount(2)
  const successful = await (await request.get(path)).json() as SubscriptionDetail
  expect(successful.source.name).toBe('知识视频 · 持续学习')
  expect(successful.source.creatorId).toBe('12345')
  expect((await (await request.get('/api/library')).json()).items).toEqual([])
  expect((await (await request.get('/api/downloads')).json()).jobs).toEqual(beforeJobs)
  await page.getByLabel('搜索订阅投稿').fill('更新后的标题')
  await expect(page.getByTestId('content-card')).toHaveCount(1)
  await page.getByRole('button', { name: '阅读 订阅测试样例：更新后的标题', exact: true }).scrollIntoViewIfNeeded()
  const readingScroll = await page.evaluate(() => scrollY)
  await page.getByRole('button', { name: '阅读 订阅测试样例：更新后的标题', exact: true }).click()
  await expect(page.getByRole('heading', { name: '我的笔记' })).toBeVisible()
  await expect(page.getByRole('list', { name: '字幕段落' })).toBeVisible()
  await page.getByRole('button', { name: '返回列表' }).click()
  await expect(page).toHaveURL(`/subscriptions?${new URLSearchParams({ q: '更新后的标题' })}`)
  await expect(page.getByLabel('搜索订阅投稿')).toHaveValue('更新后的标题')
  await expect(page.getByRole('button', { name: '阅读 订阅测试样例：更新后的标题', exact: true })).toBeFocused()
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(readingScroll)
  await page.getByLabel('搜索订阅投稿').fill('')
  await page.getByRole('button', { name: '更新投稿', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('订阅测试平台限制')
  await expect(page.getByTestId('content-card')).toHaveCount(2)
  const afterFailure = await (await request.get(path)).json() as SubscriptionDetail
  expect(afterFailure.items).toEqual(successful.items)
  expect(afterFailure.source).toEqual({ ...successful.source, refresh: afterFailure.source.refresh })
  expect(afterFailure.source.refresh).toMatchObject({ failures: 1, status: 'rate_limited', contentRevision: successful.source.refresh.contentRevision })
  // Simulate another client updating the same source, then explicitly refresh the
  // local list. Both source metadata and cached items must be re-read together.
  const externalUpdate = await request.post(`${path}/update`)
  expect(externalUpdate.status()).toBe(200)
  const latest = await externalUpdate.json() as SubscriptionDetail
  await expect(page.getByTestId('content-card').first()).toContainText('更新后的标题')
  await page.getByRole('button', { name: '重新加载来源', exact: true }).click()
  await expect(page.getByTestId('content-card').first()).toContainText('外部更新后的标题')
  await openSubscriptionAdd(page)
  await page.getByLabel('订阅地址').fill('67890')
  await page.getByLabel('订阅来源名称', { exact: true }).fill('另一个来源')
  await page.getByRole('button', { name: '保存来源', exact: true }).click()
  await expect(page.getByRole('heading', { name: '另一个来源', exact: true })).toBeVisible()
  await expect(page.getByTestId('content-card')).toHaveCount(0)
  await page.getByRole('button', { name: '更新投稿', exact: true }).click()
  await expect(page.getByTestId('content-card')).toHaveCount(1)
  await expect(page.getByTestId('content-card')).toContainText('另一个来源的订阅测试样例')
  await page.getByRole('navigation', { name: '选择订阅来源' }).getByRole('button', { name: /知识视频/ }).click()
  await expect(page.getByTestId('content-card')).toHaveCount(2)
  await expect(page.getByRole('alert')).toContainText('订阅测试平台限制')
  await page.reload()
  await expect(page.getByRole('heading', { name: '知识视频 · 持续学习', exact: true })).toBeVisible()
  await expect(page.getByTestId('content-card')).toHaveCount(2)
  expect(await (await request.get(path)).json()).toEqual(latest)
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.evaluate(() => { if (document.activeElement instanceof HTMLElement) document.activeElement.blur(); window.scrollTo(0, 0) })
  await page.getByRole('button', { name: '切换深色模式' }).click()
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.getByRole('button', { name: '切换浅色模式' }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.evaluate(() => { if (document.activeElement instanceof HTMLElement) document.activeElement.blur(); window.scrollTo(0, 0) })
  await page.getByTestId('content-card').first().getByRole('button', { name: '收藏 订阅测试样例：外部更新后的标题', exact: true }).click()
  await expect(page.getByTestId('content-card').first().getByRole('button', { name: '取消收藏 订阅测试样例：外部更新后的标题', exact: true })).toBeEnabled()
  const noteResponse = await request.post('/api/notes', { data: { contentId: 'bilibili:BV17x411w7KC', body: '订阅移除后的保留笔记测试。', positionSeconds: null } })
  expect(noteResponse.status()).toBe(201)
  const note = await noteResponse.json()
  await page.getByRole('button', { name: '移除来源', exact: true }).click()
  await page.getByRole('button', { name: '保留来源', exact: true }).click()
  await expect(page.getByRole('heading', { name: '知识视频 · 持续学习', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '移除来源', exact: true }).click()
  await page.getByRole('button', { name: '确认移除', exact: true }).click()
  await expect(page.getByRole('heading', { name: '另一个来源', exact: true })).toBeVisible()
  expect((await request.get(path)).status()).toBe(404)
  expect((await (await request.get('/api/library')).json()).items).toHaveLength(1)
  expect((await (await request.get('/api/notes?contentId=bilibili%3ABV17x411w7KC')).json()).notes.some((item: { id: string }) => item.id === note.id)).toBe(true)
  expect((await (await request.get('/api/downloads')).json()).jobs).toEqual(beforeJobs)
  await request.delete(`/api/notes/${note.id}`)
})

test('subscription validation retains input, failed first update stays unsynced, and mobile navigation works', async ({ page, request }) => {
  await page.goto('/')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '菜单' }).click()
  await page.getByRole('dialog', { name: '导航菜单' }).getByRole('button', { name: '订阅管理', exact: true }).press('Enter')
  await expect(page).toHaveURL('/subscriptions')
  await expect(page.getByRole('dialog', { name: '导航菜单' })).not.toBeVisible()
  await page.getByLabel('订阅地址').fill('BV17x411w7KC')
  await page.getByLabel('订阅来源名称', { exact: true }).fill('保留输入')
  await page.getByRole('button', { name: '保存来源', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('请输入所选来源的 UID、主页或 RSS / Atom 地址')
  await expect(page.getByLabel('订阅来源名称', { exact: true })).toHaveValue('保留输入')
  expect((await (await request.get('/api/subscriptions')).json()).sources).toEqual([])
  await page.getByLabel('订阅地址').fill('99999')
  await page.getByRole('button', { name: '保存来源', exact: true }).click()
  await expect(page.getByRole('heading', { name: '保留输入', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '更新投稿', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('订阅测试平台限制')
  await expect(page.getByText('来源已保存，暂时还没有成功获取的内容。', { exact: true })).toBeVisible()
  const detail = await (await request.get('/api/subscriptions/bilibili%3Acreator%3A99999')).json() as SubscriptionDetail
  expect(detail.source.lastUpdatedAt).toBe(0)
  expect(detail.items).toEqual([])
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
})

test('source refresh preserves an expanded add form and its unsaved draft', async ({ page, request }) => {
  const created = await request.post('/api/subscriptions', { data: { type: 'bilibili', query: '12345', name: '现有来源' } })
  expect(created.status()).toBe(201)
  await page.goto('/subscriptions')
  await page.getByRole('navigation', { name: '选择订阅来源' }).getByRole('button', { name: /现有来源/ }).click()
  await expect(page.getByRole('heading', { name: '现有来源', exact: true })).toBeVisible()
  await openSubscriptionAdd(page)
  await page.getByLabel('订阅地址').fill('67890')
  await page.getByLabel('订阅来源名称', { exact: true }).fill('未保存的第二个来源')
  const refreshed = page.waitForResponse(response => response.url().endsWith('/api/subscriptions') && response.request().method() === 'GET')
  await page.getByRole('button', { name: '重新加载来源', exact: true }).click()
  await refreshed
  await expect(page.getByLabel('订阅地址')).toBeVisible()
  await expect(page.getByLabel('订阅地址')).toHaveValue('67890')
  await expect(page.getByLabel('订阅来源名称', { exact: true })).toHaveValue('未保存的第二个来源')
  await page.getByRole('button', { name: '历史收件箱', exact: true }).click()
  await expect(page.getByLabel('订阅地址')).toBeVisible()
  await page.getByRole('button', { name: '来源管理', exact: true }).click()
  await expect(page.getByLabel('订阅来源名称', { exact: true })).toHaveValue('未保存的第二个来源')
  expect((await (await request.get('/api/subscriptions')).json()).sources).toHaveLength(1)
})

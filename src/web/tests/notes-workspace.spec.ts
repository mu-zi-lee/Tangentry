test.use({ timezoneId: 'America/Chicago' })

test.beforeEach(async ({ request }) => {
  expect((await request.put('/api/preferences/theme', { data: { value: 'light', revision: Date.now() } })).ok()).toBe(true)
  let cursor = ''
  do {
    const result = await (await request.get('/api/notes/search?' + new URLSearchParams({ cursor }))).json()
    for (const note of result.notes) expect((await request.delete('/api/notes/' + note.id)).ok()).toBe(true)
    cursor = result.nextCursor
  } while (cursor)
})

test('empty notes open a full-height writing surface and keep the first save usable across screen sizes', async ({ page, request }) => {
  await page.setViewportSize({ width: 1844, height: 1098 })
  await page.goto('/notes')
  const notebook = page.locator('.notebook')
  const memo = page.getByLabel('随手记正文', { exact: true })
  await expect(notebook).toHaveAttribute('data-empty', 'true')
  await expect(page.getByRole('region', { name: '笔记浏览', exact: true })).toBeHidden()
  await expect(memo).toBeVisible()
  expect((await memo.boundingBox())!.height).toBeGreaterThan(700)
  const tag = await page.locator('.quick-memo .note-tag-field').boundingBox()
  const footer = await page.locator('.quick-memo-footer').boundingBox()
  expect(footer!.y - tag!.y - tag!.height).toBeLessThan(20)
  expect(footer!.y + footer!.height).toBeLessThanOrEqual(1098)
  await memo.fill('第一条随手记')
  for (const width of [1050, 390]) {
    await page.setViewportSize({ width, height: 844 })
    await expect(memo).toBeVisible()
    await expect(memo).toHaveValue('第一条随手记')
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  }
  await page.getByRole('button', { name: '保存随手记', exact: true }).click()
  await expect(notebook).toHaveAttribute('data-empty', 'false')
  await expect(page.getByRole('list', { name: '全部笔记结果' })).toContainText('第一条随手记')
  expect((await (await request.get('/api/notes/search')).json()).notes).toHaveLength(1)
  await page.getByRole('button', { name: '新建随手记', exact: true }).click()
  await expect(memo).toBeVisible()
  await expect(memo).toHaveValue('')
})

test('global note deletion confirms inline, preserves editing drafts and keeps the wider editor usable', async ({ page, request }) => {
  const note = await (await request.post('/api/notes', { data: { body: '准备删除的随手记', tags: ['仅此笔记'] } })).json() as ReadingNote
  const other = await (await request.post('/api/notes', { data: { body: '保留的另一条笔记' } })).json() as ReadingNote
  await page.setViewportSize({ width: 1844, height: 1098 })
  await page.goto('/notes')
  const row = page.locator(`[data-note-id="${note.id}"]`)
  const otherRow = page.locator(`[data-note-id="${other.id}"]`)
  await row.getByRole('button', { name: /^编辑来源笔记：/ }).click()
  const editor = page.getByRole('complementary', { name: '来源笔记编辑', exact: true })
  const body = editor.getByLabel('笔记正文', { exact: true })
  await expect(body).toHaveValue(note.body)
  await body.fill('删除后也要保留的未保存草稿')
  const width = (await page.locator('.notebook-writing').boundingBox())!.width
  expect(width).toBeGreaterThanOrEqual(430)
  expect(width).toBeLessThanOrEqual(440)
  expect(await page.locator('.notebook-writing').evaluate(element => element.scrollWidth > element.clientWidth)).toBe(false)
  expect(await editor.locator('.note-list > li').evaluate(element => getComputedStyle(element).borderInlineStartWidth)).toBe('0px')
  expect(await editor.locator('.note-library-filters').evaluate(element => getComputedStyle(element).borderBottomWidth)).toBe('0px')
  expect(await editor.getByRole('group', { name: '笔记分类' }).getByRole('button', { name: /^全部/ }).evaluate(element => getComputedStyle(element).borderBottomWidth)).toBe('0px')
  const trash = row.getByRole('button', { name: /^删除笔记：/ })
  await trash.click()
  const confirmation = row.getByRole('group', { name: '删除笔记确认', exact: true })
  await expect(confirmation).toBeVisible()
  expect(await confirmation.evaluate(element => getComputedStyle(element).position)).toBe('static')
  await expect(confirmation.getByRole('button', { name: '保留笔记', exact: true })).toBeFocused()
  await confirmation.getByRole('button', { name: '保留笔记', exact: true }).click()
  await expect(confirmation).toHaveCount(0)
  await expect(trash).toBeFocused()
  await trash.click()
  await otherRow.getByRole('button', { name: /^删除笔记：/ }).click()
  await expect(page.getByRole('group', { name: '删除笔记确认', exact: true })).toHaveCount(1)
  await otherRow.getByRole('button', { name: '保留笔记', exact: true }).press('Escape')
  await expect(otherRow.getByRole('button', { name: /^删除笔记：/ })).toBeFocused()
  await trash.click()
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  const deletion = page.waitForRequest(value => value.method() === 'DELETE' && new URL(value.url()).pathname === `/api/notes/${note.id}`)
  await confirmation.getByRole('button', { name: '确认删除', exact: true }).click()
  expect(new URL((await deletion).url()).searchParams.get('expectedUpdatedAt')).toBe(String(note.updatedAt))
  await expect(row).toHaveCount(0)
  await expect(otherRow.getByRole('button', { name: /^编辑来源笔记：/ })).toBeFocused()
  await expect(editor.locator('.note-list > li')).toHaveCount(0)
  await expect(body).toHaveValue('删除后也要保留的未保存草稿')
  await expect(page.locator('.notebook-delete-notice')).toContainText('草稿仍保留')
  expect((await (await request.get('/api/notes/search')).json()).notes.map((value: ReadingNote) => value.id)).toEqual([other.id])
  await expect(page.getByLabel('筛选笔记标签', { exact: true })).toHaveCount(0)
  await editor.getByRole('button', { name: '另存为新笔记', exact: true }).click()
  await editor.getByRole('button', { name: '保存笔记', exact: true }).click()
  await expect(page.getByRole('list', { name: '全部笔记结果' })).toContainText('删除后也要保留的未保存草稿')
  const saved = (await (await request.get('/api/notes/search')).json()).notes as ReadingNote[]
  expect(saved).toHaveLength(2)
  expect(saved.find(value => value.body === '删除后也要保留的未保存草稿')?.id).not.toBe(note.id)
  await page.setViewportSize({ width: 1050, height: 844 })
  await expect(body).toBeVisible()
  expect(await page.locator('.notebook-writing').evaluate(element => element.scrollWidth > element.clientWidth)).toBe(false)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(body).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
})

test('global note deletion retains failed records and rejects edits made after confirmation opened', async ({ page, request }) => {
  const note = await (await request.post('/api/notes', { data: { body: '删除前的原始内容' } })).json() as ReadingNote
  await page.setViewportSize({ width: 1844, height: 1098 })
  await page.goto('/notes')
  const row = page.locator(`[data-note-id="${note.id}"]`)
  const trash = row.getByRole('button', { name: /^删除笔记：/ })
  await trash.click()
  const update = await request.patch(`/api/notes/${note.id}`, { data: { body: '其他窗口刚保存的新内容', expectedUpdatedAt: note.updatedAt } })
  expect(update.ok()).toBe(true)
  const updated = await update.json() as ReadingNote
  expect(updated.updatedAt).not.toBe(note.updatedAt)
  await page.getByRole('button', { name: '刷新全部笔记', exact: true }).click()
  await expect(row).toContainText(updated.body)
  await row.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(row.getByRole('alert')).toContainText('核对最新内容')
  await expect(row.getByRole('group', { name: '删除笔记确认', exact: true })).toHaveCount(0)
  await expect(trash).toBeFocused()
  expect((await (await request.get('/api/notes/search')).json()).notes[0].body).toBe(updated.body)
  await page.route(`**/api/notes/${note.id}?**`, route => route.fulfill({ status: 503, json: { code: 'test_failure', message: '测试删除失败' } }))
  await trash.click()
  await row.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(row.getByRole('alert')).toContainText('测试删除失败')
  await expect(row).toContainText(updated.body)
  await page.unroute(`**/api/notes/${note.id}?**`)
  await trash.click()
  await page.getByRole('button', { name: '切换深色模式', exact: true }).click()
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(row.getByRole('button', { name: '确认删除', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  const deletion = page.waitForRequest(value => value.method() === 'DELETE')
  await row.getByRole('button', { name: '确认删除', exact: true }).click()
  expect(new URL((await deletion).url()).searchParams.get('expectedUpdatedAt')).toBe(String(updated.updatedAt))
  await expect(row).toHaveCount(0)
  await expect(page.locator('.notebook')).toHaveAttribute('data-empty', 'true')
  await expect(page.getByLabel('随手记正文', { exact: true })).toBeVisible()
})

test('inline calendar selects inclusive local dates, supports keyboard navigation and rejects invalid input', async ({ page, request }) => {
  await request.post('/api/notes', { data: { body: '日期筛选样例' } })
  await page.setViewportSize({ width: 1844, height: 1098 })
  await page.goto('/notes')
  await page.locator('.notebook-date-filter > summary').click()
  await page.getByRole('button', { name: '选择开始日期', exact: true }).click()
  const calendar = page.getByRole('region', { name: '笔记日期范围', exact: true })
  await expect(calendar).toBeVisible()
  expect(await calendar.evaluate(element => getComputedStyle(element).position)).toBe('static')
  await page.getByLabel('日历年份', { exact: true }).fill('2026')
  await page.getByLabel('日历年份', { exact: true }).press('Tab')
  await page.getByLabel('日历月份', { exact: true }).selectOption('10')
  await calendar.locator('[data-date="2026-11-01"]').click()
  await expect(page.getByLabel('笔记开始日期', { exact: true })).toHaveValue('2026-11-01')
  await expect(calendar.locator('[data-date="2026-11-01"]')).toBeEnabled()
  await calendar.locator('[data-date="2026-11-01"]').press('ArrowRight')
  await expect(calendar.locator('[data-date="2026-11-02"]')).toBeFocused()
  await calendar.locator('[data-date="2026-11-02"]').press('ArrowLeft')
  const filtered = page.waitForRequest(value => {
    const url = new URL(value.url())
    return url.pathname === '/api/notes/search' && Boolean(url.searchParams.get('to'))
  })
  await calendar.locator('[data-date="2026-11-01"]').press('Enter')
  const params = new URL((await filtered).url()).searchParams
  expect(Number(params.get('from'))).toBe(Date.parse('2026-11-01T05:00:00Z') / 1000)
  expect(Number(params.get('to'))).toBe(Date.parse('2026-11-02T06:00:00Z') / 1000)
  await expect(calendar).toBeHidden()
  await expect(page.getByRole('button', { name: '选择结束日期', exact: true })).toBeFocused()
  const from = page.getByLabel('笔记开始日期', { exact: true })
  await from.fill('2026-02-30')
  await from.press('Enter')
  await expect(page.locator('.note-date-error')).toContainText('有效日期')
  await expect(from).toHaveAttribute('aria-invalid', 'true')
  await from.fill('2026-11-01')
  await from.press('Enter')
  await page.getByRole('button', { name: '选择开始日期', exact: true }).click()
  await expect(calendar).toBeVisible()
  await page.getByRole('button', { name: '上个月', exact: true }).click()
  await expect(page.getByLabel('日历月份', { exact: true })).toHaveValue('9')
  await calendar.locator('[data-date="2026-10-01"]').press('Escape')
  await expect(calendar).toBeHidden()
  await expect(page.getByRole('button', { name: '选择开始日期', exact: true })).toBeFocused()
  await page.getByRole('button', { name: '选择开始日期', exact: true }).click()
  await expect(calendar.getByRole('button', { name: '清除日期', exact: true })).toBeEnabled()
  await calendar.getByRole('button', { name: '清除日期', exact: true }).click()
  await expect(from).toHaveValue('')
  await expect(page.getByLabel('笔记结束日期', { exact: true })).toHaveValue('')
  await expect(page.getByRole('list', { name: '全部笔记结果' })).toContainText('日期筛选样例')
  await page.getByRole('button', { name: '选择开始日期', exact: true }).click()
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.getByRole('button', { name: '切换深色模式', exact: true }).click()
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(calendar).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
})

test('subtitle save failures expire without shifting captions and remain recoverable in source settings', async ({ page, request }) => {
  const item: ContentItem = {
    id: 'youtube:SaveError01', platform: 'youtube', platformId: 'SaveError01', kind: 'video',
    title: '字幕保存提示样例', author: '测试作者', authorId: '',
    url: 'https://www.youtube.com/watch?v=SaveError01', thumbnailUrl: '', description: '', durationSeconds: 30, publishedAt: 1720000000,
  }
  const track: SubtitleTrack = { language: 'zh-Hans', label: '中文', automatic: false, source: 'youtube', cues: [{ start: 0, end: 10, text: '提示消失后仍然可以继续阅读字幕。' }] }
  await request.post('/api/library', { data: item })
  await page.route('**/api/subtitles/youtube?**', route => route.fulfill({ json: { videoId: item.platformId, part: 1, status: 'available', tracks: [track], languages: [track] } }))
  await page.route('**/api/saved-subtitles/**', route => route.request().method() === 'PUT'
    ? route.fulfill({ status: 409, json: { code: 'subtitle_conflict', message: '测试保存冲突，请重新读取。' } })
    : route.continue())
  await page.setViewportSize({ width: 1844, height: 1098 })
  await page.goto('/reader?contentId=' + encodeURIComponent(item.id))
  const cues = page.getByRole('list', { name: '字幕段落', exact: true })
  const notice = page.locator('.subtitle-save-notice')
  await expect(cues).toContainText(track.cues[0].text)
  await expect(notice).toBeVisible()
  expect(await notice.evaluate(element => getComputedStyle(element).position)).toBe('fixed')
  const before = await cues.boundingBox()
  await expect(notice).toHaveCount(0, { timeout: 8000 })
  expect((await cues.boundingBox())!.y).toBe(before!.y)
  const sourceButton = page.getByRole('button', { name: '字幕来源与保存', exact: true })
  await expect(sourceButton).toContainText('保存失败')
  await sourceButton.click()
  const source = page.getByRole('region', { name: '字幕来源与保存', exact: true })
  await expect(source).toContainText('测试保存冲突')
  await page.unroute('**/api/saved-subtitles/**')
  await source.locator('.subtitle-save-error').getByRole('button', { name: '重新读取本机字幕', exact: true }).click()
  await expect(source.locator('.subtitle-save-error')).toHaveCount(0)
  await expect(sourceButton).not.toContainText('保存失败')
  await expect(cues).toContainText(track.cues[0].text)
})
